/** Kiểu của một bộ từ điển: chuỗi thành string, hàm giữ nguyên tham số. */
type Widen<T> = T extends string ? string : T extends (...args: infer A) => string ? (...args: A) => string : { [K in keyof T]: Widen<T[K]> };

